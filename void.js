let visible = false;
let sleepTimer = null;

function wakeCursor() {
    voidCursor.classList.remove('sleeping');
    clearTimeout(sleepTimer);
    sleepTimer = setTimeout(() => {
        if (visible) voidCursor.classList.add('sleeping');
    }, 5000);
}

window.addEventListener('mousemove', (e) => {
    voidCursor.style.transform =
        `translate3d(${e.clientX}px, ${e.clientY}px, 0) translate(-50%, -50%)`;
    if (!visible) {
        visible = true;
        voidCursor.classList.add('visible');
    }
    wakeCursor();
});

document.addEventListener('mouseleave', () => {
    visible = false;
    voidCursor.classList.remove('visible');
    clearTimeout(sleepTimer);
});

document.addEventListener('mouseover', (e) => {
    if (e.target.closest('a, button')) voidCursor.classList.add('hover');
});

document.addEventListener('mouseout', (e) => {
    if (e.target.closest('a, button')) voidCursor.classList.remove('hover');
});

let audioCtx = null;
let masterGain = null;
let soundOn = true;
let audioBuilt = false;

function buildAudio() {
    if (audioBuilt) return;
    audioBuilt = true;

    try {
        audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    } catch (e) {
        audioCtx = null;
        return;
    }

    masterGain = audioCtx.createGain();
    masterGain.gain.value = soundOn ? 0.1 : 0;
    masterGain.connect(audioCtx.destination);

    const osc1 = audioCtx.createOscillator();
    osc1.type = 'sine';
    osc1.frequency.value = 48;
    const g1 = audioCtx.createGain();
    g1.gain.value = 0.5;
    osc1.connect(g1).connect(masterGain);
    osc1.start();

    const osc2 = audioCtx.createOscillator();
    osc2.type = 'sine';
    osc2.frequency.value = 51.4;
    const g2 = audioCtx.createGain();
    g2.gain.value = 0.32;
    osc2.connect(g2).connect(masterGain);
    osc2.start();

    const bufferSize = audioCtx.sampleRate * 2;
    const noiseBuffer = audioCtx.createBuffer(1, bufferSize, audioCtx.sampleRate);
    const data = noiseBuffer.getChannelData(0);
    for (let i = 0; i < bufferSize; i++) {
        data[i] = (Math.random() * 2 - 1) * 0.4;
    }
    const noise = audioCtx.createBufferSource();
    noise.buffer = noiseBuffer;
    noise.loop = true;

    const noiseFilter = audioCtx.createBiquadFilter();
    noiseFilter.type = 'lowpass';
    noiseFilter.frequency.value = 220;

    const noiseGain = audioCtx.createGain();
    noiseGain.gain.value = 0.14;

    noise.connect(noiseFilter).connect(noiseGain).connect(masterGain);
    noise.start();
}

function resumeAudio() {
    buildAudio();
    if (audioCtx && audioCtx.state === 'suspended') {
        audioCtx.resume();
    }
}

buildAudio();

['click', 'keydown', 'touchstart', 'mousemove', 'pointerdown'].forEach(evt => {
    window.addEventListener(evt, resumeAudio, { passive: true });
});

function updateSoundButton() {
    soundToggle.textContent = soundOn ? '♪ on' : '♪ off';
    soundToggle.classList.toggle('active', soundOn);
}

soundToggle.addEventListener('click', (e) => {
    e.stopPropagation();
    soundOn = !soundOn;
    resumeAudio();
    if (masterGain && audioCtx) {
        masterGain.gain.setTargetAtTime(soundOn ? 0.1 : 0, audioCtx.currentTime, 0.08);
    }
    updateSoundButton();
});

updateSoundButton();
