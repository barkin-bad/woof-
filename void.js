let currentLang = 'ru';
let generation = 0;

function sleep(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
}

function randomWrongChar(correct) {
    const alphabet = 'абвгдежзийклмнопрстуфхцчшщъыьэюяabcdefghijklmnopqrstuvwxyz';
    let wrong;
    let guard = 0;
    do {
        wrong = alphabet[Math.floor(Math.random() * alphabet.length)];
        guard++;
    } while (wrong === correct.toLowerCase() && guard < 20);
    return wrong;
}

async function typeParagraph(p, text, lang, myGen) {
    const live = p.querySelector('.void-p-live');
    if (!live) return;
    p.dataset.state = 'typing';
    let lastIntrusionAt = -999;

    for (let i = 0; i < text.length; i++) {
        if (generation !== myGen) return;

        if (
            i - lastIntrusionAt > 60 &&
            i > 40 &&
            i < text.length - 40 &&
            Math.random() < 0.0032
        ) {
            lastIntrusionAt = i;
            await doIntrusion(p, lang, myGen);
            if (generation !== myGen) return;
        }

        if (
            Math.random() < 0.008 &&
            /[а-яёa-z]/i.test(text[i]) &&
            i > 3
        ) {
            const wrongCount = 1 + Math.floor(Math.random() * 2);
            for (let w = 0; w < wrongCount; w++) {
                live.textContent += randomWrongChar(text[i]);
                await sleep(70 + Math.random() * 60);
                if (generation !== myGen) return;
            }
            await sleep(180 + Math.random() * 160);
            for (let w = 0; w < wrongCount; w++) {
                live.textContent = live.textContent.slice(0, -1);
                await sleep(50);
                if (generation !== myGen) return;
            }
        }

        live.textContent += text[i];

        let delay = 16 + Math.random() * 14;
        if (',;:'.includes(text[i])) delay += 90;
        if ('.!?—'.includes(text[i])) delay += 220;
        if (text[i] === ' ') delay += 6;
        await sleep(delay);
    }

    if (generation !== myGen) return;
    p.dataset.state = 'done';
}

async function doIntrusion(paragraphEl, lang, myGen) {
    const list = content[lang].intrusions;
    const pick = list[Math.floor(Math.random() * list.length)];

    const ghost = document.createElement('div');
    ghost.className = 'ghost-line' + (pick.loud ? ' loud' : '');
    paragraphEl.after(ghost);

    for (const ch of pick.text) {
        if (generation !== myGen) { ghost.remove(); return; }
        ghost.textContent += ch;
        await sleep(45 + Math.random() * 55);
    }

    await sleep(1400 + Math.random() * 900);
    if (generation !== myGen) { ghost.remove(); return; }

    while (ghost.textContent.length > 0) {
        if (generation !== myGen) { ghost.remove(); return; }
        ghost.textContent = ghost.textContent.slice(0, -1);
        await sleep(28);
    }

    await sleep(200);
    ghost.remove();
}

const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        const el = entry.target;
        if (!entry.isIntersecting) return;
        if (el.dataset.state !== 'idle') return;

        const idx = parseInt(el.dataset.idx, 10);
        const block = content[currentLang].blocks[idx];
        if (!block || block.type !== 'p') return;

        const myGen = generation;
        typeParagraph(el, block.text, currentLang, myGen);
        observer.unobserve(el);
    });
}, { threshold: 0.1 });

function makeParagraph(idx, fullText) {
    const p = document.createElement('p');
    p.dataset.idx = idx;
    p.dataset.state = 'idle';

    const reserve = document.createElement('span');
    reserve.className = 'void-p-reserve';
    reserve.setAttribute('aria-hidden', 'true');
    reserve.textContent = fullText;

    const live = document.createElement('span');
    live.className = 'void-p-live';

    p.appendChild(reserve);
    p.appendChild(live);
    return p;
}

function renderArticle(lang) {
    generation++;
    currentLang = lang;

    article.innerHTML = '';

    const c = content[lang];

    const h1 = document.createElement('h1');
    h1.textContent = c.title;
    article.appendChild(h1);

    c.blocks.forEach((block, idx) => {
        if (block.type === 'p') {
            article.appendChild(makeParagraph(idx, block.text));
        } else if (block.type === 'figure') {
            const fig = document.createElement('figure');
            fig.className = 'void-figure void-figure-' + block.size;
            const img = document.createElement('img');
            img.src = block.src;
            img.alt = '';
            fig.appendChild(img);
            article.appendChild(fig);
        }
    });

    observer.disconnect();
    document.querySelectorAll('.void-article p[data-idx]').forEach(p => {
        observer.observe(p);
    });
}

function setLang(lang) {
    if (!content[lang]) return;
    document.documentElement.lang = lang === 'ru' ? 'ru' : 'en';
    langButtons.forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    try { localStorage.setItem('voidLang', lang); } catch (e) {}
    renderArticle(lang);
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

langButtons.forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
});

